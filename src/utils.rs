// Function to print help
pub fn print_help(exit_code: i32) {
    // Collect PSP_* active variables
    let mut psp_vars: Vec<String> = vec![];
    for var in dotenvy::vars() {
        if var.0.contains("PSP_") {
            psp_vars.push(var.0);
        }
    }
    print_logo();
    println!("psp (Python Scaffolding Projects), version {VERSION}");
    println!("usage: psp [shortcut]");
    println!("ie: psp [help|quick|simple|full]");
    // Print complete help
    if exit_code == 0 {
        println!(
            "
shortcut:
    help:   print this help message
    quick:  enables a rapid setup (few options included)
    simple: enables a basic setup (only Python package)
    full:   enables a full setup (all options included)

links:
    repository:     https://github.com/MatteoGuadrini/psp
    documentation:  https://psp.readthedocs.io/

templates:
    cache:  {}
    folder: {}

variables:
    {psp_vars:?}

environments:
    Python version: {}",
            env_pspcache(),
            env_psptemplatepath(),
            get_python_version()
        );
    }
    exit(exit_code)
}

// Function that captures a keyword argument
pub fn get_shortcut() -> String {
    let args: Vec<String> = args().collect();
    if args.len() > 1 {
        let shortcut = &args[1];
        if !ARGS.contains(&shortcut.as_str()) {
            error(format!("unknown shortcut command `{shortcut}`"));
            print_help(1);
        }
        shortcut.clone()
    } else {
        "None".to_string()
    }
}

// Function to get home directory
fn home_dir() -> String {
    #[cfg(any(target_os = "linux", target_os = "macos"))]
    let home_var_name = "HOME";
    #[cfg(target_os = "windows")]
    let home_var_name = "USERPROFILE";
    var(home_var_name).unwrap()
}

// Function to load env files
pub fn load_env() {
    // Load first, .env file from the current working directory
    dotenv().ok();
    // Load the second, .psp.env file from home
    let home_var = home_dir();
    let home_env = Path::new(home_var.as_str()).join(".psp.env");
    dotenvy::from_filename(home_env).ok();
}

// Function to render a template file
pub fn render_template(template: &str, file: &str, data: HashMap<&str, &str>) -> bool {
    // Create template file
    let tmp_dir = temp_dir().join("psp_templates");
    let template_path = tmp_dir.join(template).display().to_string();
    create_template(template, tmp_dir.to_str().unwrap());
    let mut handlebars = Handlebars::new();
    if let Err(e) = handlebars.register_template_file(template, &template_path) {
        error(format!("{e}; {template} is not found!"));
        return false;
    }
    let mut output_file = File::create(file).unwrap();
    // Replace variables into file
    let file_ret = handlebars.render_to_write(template, &data, &mut output_file);
    remove_file(template).ok();
    if file_ret.is_err() {
        false
    } else {
        true
    }
}

// Function to make a command
pub fn make_command(
    bin: &str,
    root: &str,
    start_path: &str,
    args: Vec<String>,
    venv: bool,
) -> std::process::Command {
    // Create start path if not exists
    let dir_ret = make_dirs(start_path);
    if let Err(e) = dir_ret {
        error(format!("start path folder creation error: {e}"));
    }
    let mut command = std::process::Command::new(bin);
    // Activate venv
    #[cfg(any(target_os = "linux", target_os = "macos"))]
    let bin_folder = "bin";
    #[cfg(target_os = "windows")]
    let bin_folder = "Scripts";
    if venv {
        command.env(
            "PATH",
            join_env_path(
                Path::new(absolute(root).unwrap().display().to_string().as_str())
                    .join(".venv")
                    .join(bin_folder)
                    .display()
                    .to_string(),
            ),
        );
    }
    command.args(&args).current_dir(start_path);
    command
}

