// Function to check if template repository is remote url or local folder
fn check_templates_is_url(templates: &str) -> bool {
    if templates.starts_with("http") {
        return true;
    }
    false
}

// Function to create cache folder
pub fn create_cache_dir() -> String {
    let home_var = home_dir();
    let cache_dir = Path::new(home_var.as_str()).join(".psp_cache");
    if !cache_dir.exists() {
        let dir_ret = make_dirs(&cache_dir.display().to_string());
        if let Err(e) = dir_ret {
            error(format!("cache template folder creation error: {e}"));
        }
    }
    cache_dir.display().to_string()
}

// Function to download/copy template
fn create_template(template: &str, destination: &str) {
    let mut fallback: bool = true;
    let templates = env_psptemplatepath();
    let cache_template = env_pspcache();
    let template_repo = format!("{templates}/{template}");
    let destination_template = Path::new(destination).join(template);
    if templates != TEMPLATES {
        if check_templates_is_url(&template_repo) {
            // Download custom template
            if !get_file_from_url(&template_repo, destination, template) {
                fallback = true;
            }
        } else {
            // Copy custom local template
            let template_repo = Path::new(template).join(template);
            if let Err(err) = copy(&template_repo, &destination_template) {
                error(format!("copy template {template} error ({err})"));
                fallback = true;
            }
        }
    } else if cache_template {
        let cache_dir = create_cache_dir();
        let cached_template = Path::new(cache_dir.as_str()).join(template);
        if cached_template.exists() {
            if let Err(err) = copy(&cached_template, &destination_template) {
                error(format!("copy cache template {template} error ({err})"));
                fallback = true;
            }
        }
    } else {
        fallback = true;
    }
    if fallback {
        // Fallback
        get_file_from_url(template_repo.as_str(), destination, template);
    }
    // Check cache (copy to cache)
    if cache_template {
        let cache_dir = create_cache_dir();
        let cached_template = Path::new(cache_dir.as_str()).join(template);
        if !cached_template.exists() {
            if let Err(err) = copy(&destination_template, &cached_template) {
                error(format!("create cache template {template} error ({err})"));
            }
        }
    }
}

// Function to make build system settings
pub fn make_builder(root: &str, venv: bool) -> String {
    // Check environment variable for build
    let builder = env_pybuild();
    // Check if a builder is supported and installed
    if !check_builder(builder.as_str(), root, venv) {
        warning("fallback builder to `setuptools`".to_string());
    }
    let build_settings: String;
    if builder == "poetry" {
        // poetry
        build_settings = "
[build-system]
requires = ['poetry-core']
build-backend = 'poetry.core.masonry.api'"
            .to_string();
    } else if builder == "hatch" {
        // hatch
        build_settings = "
[build-system]
requires = ['hatchling']
build-backend = 'hatchling.build'"
            .to_string();
    } else if builder == "maturin" {
        // maturin
        build_settings = "
[build-system]
requires = ['maturin>=1.0,<2.0']
build-backend = 'maturin'
"
        .to_string();
    } else {
        // setuptools: defualt
        build_settings = "
[build-system]
requires = ['setuptools', 'wheel']
build-backend = 'setuptools.build_meta'"
            .to_string();
    }
    build_settings
}

// Function check another package manager
fn check_pm(pm: &str) -> bool {
    // Check if a package manager is supported
    if pm != PIP_BIN && !SUPPORTED_PM.contains(&pm) {
        error(format!("package manager `{pm}` is not supported"));
        return false;
    }
    // Check if package manager is avalaible
    if !check_tool(pm) {
        error(format!("package manager `{pm}` is not supported"));
        return false;
    }
    true
}

// Function check another builder
fn check_builder(builder: &str, root: &str, venv: bool) -> bool {
    // Check if a builder is supported
    if builder != "setuptools" && !SUPPORTED_BUILDER.contains(&builder) {
        error(format!("builder `{builder}` is not supported"));
        return false;
    }
    // Check if builder is avalaible
    if builder != "setuptools" && !check_tool(builder) {
        warning(format!("builder `{builder}` is not installed"));
        // Install builder
        let mut pip = make_pm(PIP_BIN, root, root, vec![builder.to_string()], venv);
        let output = pip
            .output()
            .expect(format!("{PIP_BIN} should be installed").as_str());
        if !output.status.success() {
            error(format!(
                "builder `{builder}` installatioon failed; use fallback"
            ));
            return false;
        }
    }
    true
}

// Function make package manager command
pub fn make_pm(
    pm: &str,
    root: &str,
    start_path: &str,
    pkgs: Vec<String>,
    venv: bool,
) -> std::process::Command {
    // Define binary for package manager
    let bin = if pm.to_lowercase() == "conda" {
        #[cfg(any(target_os = "linux", target_os = "macos"))]
        let bin = "conda";
        #[cfg(target_os = "windows")]
        let bin = "conda.exe";
        bin
    } else if pm.to_lowercase() == "uv" {
        #[cfg(any(target_os = "linux", target_os = "macos"))]
        let bin = "uv";
        #[cfg(target_os = "windows")]
        let bin = "uv.exe";
        bin
    } else {
        let bin = PIP_BIN;
        bin
    };
    // Define arguments for package manager
    let mut args: Vec<String> = vec![];
    if pm.to_lowercase() == "conda" {
        args.extend(vec!["install".to_string()]);
    } else if pm.to_lowercase() == "uv" {
        args.extend(vec!["pip".to_string(), "install".to_string()]);
    } else {
        args.extend(vec![
            "install".to_string(),
            "--timeout=10".to_string(),
            "--retries=1".to_string(),
        ]);
    }
    args.extend(pkgs.clone());
    // Check if a package manager is supported and installed
    if !check_pm(bin) {
        warning(format!("fallback package manager to `{PIP_BIN}`"));
    }
    // Make command
    make_command(bin, root, start_path, args, venv)
}
