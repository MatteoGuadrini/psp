// Function to split PATH environment variable
fn split_env_path() -> Vec<String> {
    let env_paths = var("PATH").ok().unwrap();
    #[cfg(any(target_os = "linux", target_os = "macos"))]
    let paths: Vec<String> = env_paths.split(':').map(String::from).collect();
    #[cfg(target_os = "windows")]
    let paths: Vec<String> = env_paths.split(';').map(String::from).collect();
    paths
}

// Function to join a path into the environment PATH variable
fn join_env_path(path: String) -> String {
    let mut paths = split_env_path();
    paths.insert(0, path);
    #[cfg(any(target_os = "linux", target_os = "macos"))]
    let separator: String = String::from(":");
    #[cfg(target_os = "windows")]
    let separator: String = String::from(";");
    paths.join(&separator)
}

// Function to check if a tool is installed
pub fn check_tool(tool: &str) -> bool {
    let paths: Vec<String> = split_env_path();
    for path in paths {
        let tool_path = Path::new(&path).join(tool);
        if Path::new(&tool_path).exists() {
            return true;
        }
    }
    false
}

// Function to create folders and parents
pub fn make_dirs(dir: &str) -> std::io::Result<()> {
    let result = create_dir_all(dir);
    if let Err(e) = result {
        error(format!("{e}"));
        exit(2);
    } else {
        Ok(())
    }
}

// Function to create a file with contents
pub fn make_file(file: &str, content: String) -> std::io::Result<()> {
    let mut file = File::create(file)?;
    let result = file.write_all(&content.as_bytes());
    if let Err(e) = result {
        error(format!("{e}"));
        exit(3);
    } else {
        Ok(())
    }
}

// Function to write the update log
pub fn write_log(log: &str, content: &str) {
    if env_psplog() {
        let mut file = OpenOptions::new()
            .append(true)
            .create(true)
            .open(log)
            .unwrap();
        writeln!(file, "{}", content).ok();
    }
}

// Function to delete the log
pub fn delete_log(log: &str) {
    if env_psplog() {
        let log_deletion = remove_file(log);
        if let Err(err) = log_deletion {
            error(format!("deletion log {log} failed; {err}"));
        }
    }
}

// Function to read the update log
pub fn read_log(log: &str) -> std::io::Result<String> {
    let mut file = File::open(log)?;
    let mut contents = String::new();
    file.read_to_string(&mut contents).ok();
    Ok(contents)
}

// Function to create Python file
pub fn create_python_file(file: &str, content: &str) -> bool {
    // Make file structures
    let py_file_ret = make_file(
        file,
        format!(
            "#! /usr/bin/env python3
# -*- encoding: utf-8 -*-
# vim: se ts=4 et syn=python:
# {SIGNATURE}, version {VERSION}

{content}"
        ),
    );
    if let Err(e) = py_file_ret {
        error(format!("{e}"));
        return false;
    }
    true
}

// Function to create Python package folder
pub fn create_python_package(path: &Path, content: &str) -> bool {
    let dir_ret = make_dirs(path.display().to_string().as_str());
    if let Err(e) = dir_ret {
        error(format!("{e}"));
        return false;
    }
    // Make file structures
    let init_file = path.join("__init__.py");
    if !create_python_file(init_file.display().to_string().as_str(), content) {
        error("`__init__.py` creation failed".to_string());
        return false;
    }
    true
}

// Function to check line into log
pub fn check_log(step: &str, log: &str) -> bool {
    let mut result = false;
    if env_psplog() && std::fs::exists(log).ok().unwrap() {
        let log_content = read_log(log);
        result = log_content.unwrap().contains(step);
    }
    result
}

// Function to get wrote values from log
pub fn get_log_value(step: &str, log: &str) -> Option<String> {
    // Find the line that starts with the step name
    log.lines()
        .find(|line| line.starts_with(step))
        .and_then(|line| {
            // Find the colon in that line
            let colon_pos = line.find(':')?;
            // Extract and trim the value after the colon
            Some(line[colon_pos + 1..].trim().to_string())
        })
}

// Function to get a Python version <MAJOR.MINOR>
pub fn get_python_version() -> String {
    let mut python = make_command(PYTHON_BIN, ".", ".", vec!["--version".to_string()], false);
    let output = python
        .output()
        .expect(format!("{PYTHON_BIN} should be installed").as_str());
    let version = std::str::from_utf8(&output.stdout)
        .unwrap()
        .replace("Python", "")
        .replace(" ", "")
        .replace("\n", "");
    format!("{}", &version[..4])
}

// Function to get file from url
pub fn get_file_from_url(url: &str, start_path: &str, output_file: &str) -> bool {
    #[cfg(any(target_os = "linux", target_os = "macos"))]
    let command = "curl";
    #[cfg(target_os = "windows")]
    let command = "powershell.exe";
    #[cfg(any(target_os = "linux", target_os = "macos"))]
    let command_args = vec![
        format!("-o{output_file}"),
        "-k".to_string(),
        "--fail".to_string(),
        "--create-dirs".to_string(),
        "--connect-timeout".to_string(),
        "10".to_string(),
        url.to_string(),
    ];
    #[cfg(target_os = "windows")]
    let command_args = vec![
        "-NoProfile".to_string(),
        "-ExecutionPolicy".to_string(),
        "Bypass".to_string(),
        "-Command".to_string(),
        "iwr".to_string(),
        "-TimeoutSec".to_string(),
        "10".to_string(),
        "-OutFile".to_string(),
        format!("( New-Item -Path '{output_file}' -Force )"),
        url.to_string(),
    ];
    let mut downloader = make_command(command, ".", start_path, command_args, false);
    let output = downloader
        .output()
        .expect(format!("{command} should be installed").as_str());
    // Check if the command exits successfully
    if !output.status.success() {
        error(format!("`{output_file}` download failed from `{url}`"));
        return false;
    }
    true
}

// Function for prompt text
pub fn prompt_text(question: &str, default: &str, help: &str) -> String {
    let answer = if help != "None" && default != "None" {
        Text::new(question)
            .with_help_message(help)
            .with_default(default)
            .prompt()
    } else if help != "None" {
        Text::new(question).with_help_message(help).prompt()
    } else if default != "None" {
        Text::new(question).with_default(default).prompt()
    } else {
        Text::new(question).prompt()
    };
    answer.unwrap().to_string()
}

// Function for prompt confirmation (yes/no)
pub fn prompt_confirm(question: &str, default: bool, help: &str) -> bool {
    let answer = if help != "None" {
        Confirm::new(question)
            .with_default(default)
            .with_help_message(help)
            .prompt()
    } else {
        Confirm::new(question).with_default(default).prompt()
    };
    answer.unwrap()
}

// Function for prompt selections
pub fn prompt_select(question: &str, options: Vec<&str>, help: &str) -> String {
    let answer = if help != "None" {
        Select::new(question, options)
            .with_help_message(help)
            .prompt()
    } else {
        Select::new(question, options).prompt()
    };
    answer.unwrap().to_string()
}

